/** Deterministic encodings applied to every base payload. */
const VARIANTS: ReadonlyArray<(p: string) => string> = [
  (p) => p,
  (p) => p.toUpperCase(),
  (p) => p.replace(/</g, '&lt;').replace(/>/g, '&gt;'),
  (p) => encodeURIComponent(p),
  (p) => p.replace(/script/gi, 'scr\u0000ipt'),
  (p) => `\t\n ${p} \r\n`,
];

export const XSS_CORPUS: readonly string[] = [
  ...new Set(BASE.flatMap((payload) => VARIANTS.map((variant) => variant(payload)))),
];

